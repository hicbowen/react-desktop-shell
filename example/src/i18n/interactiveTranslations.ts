export function useDemoCopy() {
  const { locale } = useDemoI18n()
  return useCallback(
    (text: string) => localizeInteractiveText(locale, text),
    [locale],
  )
}

export function localizeInteractiveText(
  locale: 'zh-CN' | 'en-US',
  text: string,
) {
  return locale === 'zh-CN' ? (zhCNInteractiveText[text] ?? text) : text
}
